-- Run as EIM_APPS (or a DBA acting on its behalf).
-- The MCP runtime never executes this DDL.

CREATE TABLE EIM_APPS.EIM_DQ_RECON_SUMMARY (
    RUN_ID                    VARCHAR2(32)    NOT NULL,
    RULE_ID                   VARCHAR2(200)   NOT NULL,
    RULE_NAME                 VARCHAR2(500)   NOT NULL,
    DIMENSION                 VARCHAR2(200),
    ATTRIBUTE_NAME            VARCHAR2(500),
    SOURCE_DATABASE           VARCHAR2(30)    NOT NULL,
    POPULATION_SIGNATURE      VARCHAR2(64)    NOT NULL,
    TOTAL_SQL_SIGNATURE       VARCHAR2(64)    NOT NULL,
    DETAIL_SQL_SIGNATURE      VARCHAR2(64)    NOT NULL,
    TOTAL_RECORDS             NUMBER(19)      NOT NULL,
    FAILED_RECORDS            NUMBER(19)      NOT NULL,
    PASSED_RECORDS            NUMBER(19)      NOT NULL,
    PASS_PERCENTAGE           NUMBER(7,2)     NOT NULL,
    FAILURE_PERCENTAGE        NUMBER(7,2)     NOT NULL,
    SEVERITY                  VARCHAR2(20)     NOT NULL,
    TREND_STATUS              VARCHAR2(30)     NOT NULL,
    CHANGE_PERCENTAGE_POINTS  NUMBER(7,2),
    SOURCE_OBJECTS_JSON       CLOB,
    REPORT_MARKDOWN           CLOB,
    EXECUTED_BY               VARCHAR2(100)   NOT NULL,
    EXECUTED_AT               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CREATED_AT                TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EIM_DQ_RECON_SUMMARY PRIMARY KEY (RUN_ID, RULE_ID),
    CONSTRAINT CK_EIM_DQ_RECON_COUNTS CHECK (
        TOTAL_RECORDS >= 0
        AND FAILED_RECORDS >= 0
        AND PASSED_RECORDS >= 0
        AND FAILED_RECORDS <= TOTAL_RECORDS
    ),
    CONSTRAINT CK_EIM_DQ_RECON_PCT CHECK (
        PASS_PERCENTAGE BETWEEN 0 AND 100
        AND FAILURE_PERCENTAGE BETWEEN 0 AND 100
    ),
    CONSTRAINT CK_EIM_DQ_RECON_OBJECTS_JSON CHECK (
        SOURCE_OBJECTS_JSON IS JSON
    )
);

CREATE INDEX EIM_APPS.IX_EIM_DQ_RECON_TREND
    ON EIM_APPS.EIM_DQ_RECON_SUMMARY (
        RULE_ID, SOURCE_DATABASE, POPULATION_SIGNATURE, EXECUTED_AT
    );

CREATE TABLE EIM_APPS.EIM_DQ_FAILED_RECORDS (
    RUN_ID                VARCHAR2(32)    NOT NULL,
    RULE_ID               VARCHAR2(200)   NOT NULL,
    DETAIL_SEQUENCE       NUMBER(19)      NOT NULL,
    SYSTEM_SERIAL_NUMBER  VARCHAR2(500),
    SOURCE_RECORD_KEY     VARCHAR2(1000),
    FAILURE_REASON        VARCHAR2(2000)  NOT NULL,
    DQ_ATTRIBUTES_JSON    CLOB,
    CAPTURED_AT           TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EIM_DQ_FAILED_RECORDS
        PRIMARY KEY (RUN_ID, RULE_ID, DETAIL_SEQUENCE),
    CONSTRAINT FK_EIM_DQ_FAILED_RECON
        FOREIGN KEY (RUN_ID, RULE_ID)
        REFERENCES EIM_APPS.EIM_DQ_RECON_SUMMARY (RUN_ID, RULE_ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_EIM_DQ_FAILED_ATTR_JSON CHECK (
        DQ_ATTRIBUTES_JSON IS JSON
    )
);

CREATE INDEX EIM_APPS.IX_EIM_DQ_FAILED_SERIAL
    ON EIM_APPS.EIM_DQ_FAILED_RECORDS (
        SYSTEM_SERIAL_NUMBER, RULE_ID, CAPTURED_AT
    );

-- Replace EIM_DQ_WRITER with the approved service account. It intentionally
